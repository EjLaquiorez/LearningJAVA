/*
===============================================================================
                    SOFTWARE ENGINEER VOCABULARY ROADMAP
===============================================================================

Goal:
Train yourself to think and communicate like a professional software engineer.

As you solve programming problems, replace everyday words with engineering
vocabulary. The objective is not to sound more technical—it is to communicate
your ideas clearly, precisely, and professionally.

Think of these words as your "Engineering Toolbox."

===============================================================================
ENGINEERING VERBS
===============================================================================

[ ] Validate      → Check whether input satisfies required rules.
                    Example: Validate user input.

[ ] Verify        → Confirm that information is true or authentic.
                    Example: Verify the user's email address.

[ ] Authenticate  → Confirm the identity of a user or system.
                    Example: Authenticate the user's credentials.

[ ] Authorize     → Determine whether an authenticated user has permission.
                    Example: Authorize access to the admin dashboard.

[ ] Process       → Perform a business operation or execute a request.
                    Example: Process the payment transaction.

[ ] Generate      → Create something automatically.
                    Example: Generate an invoice or receipt.

[ ] Retrieve      → Obtain existing information from storage.
                    Example: Retrieve customer information.

[ ] Persist       → Save data permanently.
                    Example: Persist user information to the database.

[ ] Update        → Modify existing information.
                    Example: Update the user's profile.

[ ] Delete        → Remove information permanently.
                    Example: Delete an expired session.

[ ] Accept        → Allow a valid request to continue.
                    Example: Accept the registration request.

[ ] Reject        → Deny an invalid or unauthorized request.
                    Example: Reject duplicate usernames.

[ ] Redirect      → Send the user to another page or resource.
                    Example: Redirect the user to the dashboard.

[ ] Notify        → Inform the user or another system.
                    Example: Notify the customer of a successful payment.

[ ] Synchronize   → Keep multiple systems or data consistent.
                    Example: Synchronize inventory across warehouses.

[ ] Retry         → Attempt an operation again after failure.
                    Example: Retry the network request.

[ ] Roll Back     → Undo changes after an unsuccessful operation.
                    Example: Roll back the transaction.

[ ] Handle        → Respond appropriately to an event or error.
                    Example: Handle invalid user input.

[ ] Enforce       → Apply and guarantee business rules.
                    Example: Enforce password complexity requirements.

[ ] Maintain      → Keep data accurate, secure, and consistent.
                    Example: Maintain data integrity.

[ ] Preserve      → Keep information unchanged or prevent data loss.
                    Example: Preserve user input after a network failure.

===============================================================================
ENGINEERING MINDSET
===============================================================================

❌ Don't describe the code.
    "Use an if statement."

✅ Describe the behavior.
    "Reject invalid requests."

--------------------------------------------

❌ Don't describe the implementation.
    "Create an array."

✅ Describe the purpose.
    "Store multiple records."

--------------------------------------------

❌ Don't describe the syntax.
    "Loop through the list."

✅ Describe the operation.
    "Process each record."

--------------------------------------------

❌ Don't describe the programming construct.
    "Print an error."

✅ Describe the system behavior.
    "Display an appropriate validation message."

===============================================================================
MISSION
===============================================================================

Every day, choose ONE engineering verb.

1. Learn its meaning.
2. Use it in at least five different sentences.
3. Replace everyday wording with professional engineering language.
4. Apply it when explaining your algorithms and software designs.

Small improvements every day lead to professional communication.

Remember:

Great developers don't just write clean code...
They communicate ideas with clarity, precision, and confidence.

===============================================================================
*/